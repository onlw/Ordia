//! Extraction and byte-identical storage of unrecognized OOXML package parts and glue metadata.

use crate::error::XlsxError;
use quick_xml::events::Event;
use quick_xml::{Reader, XmlVersion};
use std::collections::{BTreeMap, BTreeSet};
use std::io::{Cursor, Read};

/// An individual OPC `<Relationship>` element preserved from a `.rels` file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct RawRelationship {
    /// Original relationship identifier (e.g. `"rId5"`).
    pub orig_id: String,
    /// Relationship type URI.
    pub rel_type: String,
    /// Relative or external target path/URI.
    pub target: String,
    /// Optional `TargetMode` attribute (e.g. `"External"`).
    pub target_mode: Option<String>,
}

/// Preserved `<pivotCache>` entry linking `xl/workbook.xml` to a `pivotCacheDefinition` part.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PivotCacheEntry {
    /// Numeric `cacheId` attribute in `<pivotCache cacheId="..."/>`.
    pub cache_id: String,
    /// Original `r:id` attribute in `xl/workbook.xml`.
    pub orig_rid: String,
    /// Normalized ZIP path to `xl/pivotCache/pivotCacheDefinition*.xml`.
    pub definition_part: String,
    /// Worksheet name referenced by `<worksheetSource sheet="..."/>`, if worksheet-backed.
    pub source_sheet: Option<String>,
    /// Cell range string (e.g. `"A1:D10"`) referenced by `<worksheetSource ref="..."/>`.
    pub source_ref: Option<String>,
}

/// Worksheet-level preserved attachments keyed by stable `sheetId`.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct SheetAttachments {
    /// Original sheet display name when the package was loaded.
    pub orig_name: String,
    /// Non-hyperlink relationships from `xl/worksheets/_rels/sheetN.xml.rels`.
    pub extra_rels: Vec<RawRelationship>,
    /// Original `r:id` from `<drawing r:id="..."/>`, if present.
    pub drawing_orig_rid: Option<String>,
    /// Original `r:id` from `<legacyDrawing r:id="..."/>`, if present.
    pub legacy_drawing_orig_rid: Option<String>,
    /// Original `r:id`s from `<tableParts><tablePart r:id="..."/></tableParts>`.
    pub table_part_orig_rids: Vec<String>,
    /// Raw XML of preserved `<ext>...</ext>` blocks inside worksheet `<extLst>` (e.g. slicers).
    pub preserved_ext_blocks: Vec<String>,
}

/// Source worksheet reference extracted from a preserved chart XML (`<f>Sheet1!$A$1:$B$6</f>`).
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct ChartSourceRef {
    /// Chart part path inside the ZIP (e.g. `"xl/charts/chart1.xml"`).
    pub chart_part: String,
    /// Referenced worksheet name.
    pub sheet_name: String,
    /// Raw formula reference string.
    pub formula_ref: String,
}

/// Raw bytes and ZIP storage metadata of an unrecognized package part.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct PreservedPart {
    /// Exact uncompressed part payload bytes.
    pub bytes: Vec<u8>,
    /// Whether the original entry used `Stored` (uncompressed) rather than `Deflated`.
    pub stored_uncompressed: bool,
}

/// Complete preservation snapshot extracted from an input `.xlsx` / `.xlsm` archive.
#[derive(Debug, Clone, Default)]
pub struct PreservedPackage {
    /// Exact raw bytes for every part NOT regenerated by the calculation engine.
    pub unknown_parts: BTreeMap<String, PreservedPart>,
    /// Original `ContentType` of `/xl/workbook.xml` (preserves `.xlsm` macro-enabled main type).
    pub workbook_content_type: Option<String>,
    /// Additional `<Default Extension="..." ContentType="..."/>` entries.
    pub extra_content_type_defaults: Vec<(String, String)>,
    /// Additional `<Override PartName="..." ContentType="..."/>` entries for preserved parts.
    pub extra_content_type_overrides: Vec<(String, String)>,
    /// Extra package-level relationships from `_rels/.rels`.
    pub extra_root_rels: Vec<RawRelationship>,
    /// Extra workbook-level relationships from `xl/_rels/workbook.xml.rels`.
    pub extra_workbook_rels: Vec<RawRelationship>,
    /// Optional `<workbookPr .../>` raw XML snippet (e.g. `codeName="ThisWorkbook"` for VBA).
    pub workbook_pr_xml: Option<String>,
    /// Preserved `<pivotCache>` entries and their parsed data-source metadata.
    pub pivot_caches: Vec<PivotCacheEntry>,
    /// Raw XML of preserved `<ext>...</ext>` blocks inside `xl/workbook.xml` `<extLst>`.
    pub workbook_ext_blocks: Vec<String>,
    /// Per-worksheet preserved relationships and trailing XML anchors keyed by `sheetId`.
    pub sheet_attachments: BTreeMap<u32, SheetAttachments>,
    /// Worksheet formula references discovered inside preserved `xl/charts/chart*.xml` parts.
    pub chart_refs: Vec<ChartSourceRef>,
}

impl PreservedPackage {
    /// Parses a `.xlsx` / `.xlsm` archive in memory and extracts all unknown parts and glue metadata.
    pub fn from_zip_bytes(bytes: &[u8]) -> Result<Self, XlsxError> {
        let mut archive = zip::ZipArchive::new(Cursor::new(bytes))?;
        let mut raw_entries: BTreeMap<String, (Vec<u8>, bool)> = BTreeMap::new();

        for idx in 0..archive.len() {
            let mut file = archive.by_index(idx)?;
            if file.is_dir() {
                continue;
            }
            let name = file.name()?.trim_start_matches('/').to_string();
            let stored = file.compression() == zip::CompressionMethod::Stored;
            let mut buf = Vec::with_capacity(file.size() as usize);
            file.read_to_end(&mut buf)?;
            raw_entries.insert(name, (buf, stored));
        }

        let mut pkg = Self::default();

        // 1. Classify unknown parts vs engine-managed parts.
        for (path, (part_bytes, stored)) in &raw_entries {
            if !is_engine_managed_part(path) {
                pkg.unknown_parts.insert(
                    path.clone(),
                    PreservedPart {
                        bytes: part_bytes.clone(),
                        stored_uncompressed: *stored,
                    },
                );
            }
        }

        // 2. Parse `[Content_Types].xml`.
        if let Some((ct_bytes, _)) = raw_entries.get("[Content_Types].xml") {
            parse_content_types(ct_bytes, &mut pkg)?;
        }

        // 3. Parse `_rels/.rels` for extra root relationships (e.g. customXml).
        if let Some((root_rels, _)) = raw_entries.get("_rels/.rels") {
            for rel in parse_relationships(root_rels)? {
                if !is_engine_root_rel_type(&rel.rel_type) {
                    pkg.extra_root_rels.push(rel);
                }
            }
        }

        // 4. Parse `xl/_rels/workbook.xml.rels` and `xl/workbook.xml`.
        let wb_rels = match raw_entries.get("xl/_rels/workbook.xml.rels") {
            Some((b, _)) => parse_relationships(b)?,
            None => Vec::new(),
        };
        let mut wb_rid_to_target: BTreeMap<String, String> = BTreeMap::new();
        for rel in wb_rels {
            wb_rid_to_target.insert(rel.orig_id.clone(), normalize_xl_target(&rel.target));
            if !is_engine_workbook_rel_type(&rel.rel_type) {
                pkg.extra_workbook_rels.push(rel);
            }
        }

        let mut sheet_entries: Vec<(u32, String, String)> = Vec::new(); // (sheet_id, name, sheet_part_path)
        if let Some((wb_bytes, _)) = raw_entries.get("xl/workbook.xml") {
            parse_workbook_xml(wb_bytes, &wb_rid_to_target, &mut sheet_entries, &mut pkg)?;
        }

        // Enrich PivotCache entries with `<worksheetSource>` metadata from `pivotCacheDefinition*.xml`.
        for pc in &mut pkg.pivot_caches {
            if let Some((pc_bytes, _)) = raw_entries.get(&pc.definition_part) {
                let (src_sheet, src_ref) = parse_pivot_cache_source(pc_bytes)?;
                pc.source_sheet = src_sheet;
                pc.source_ref = src_ref;
            }
        }

        // 5. Parse per-worksheet relationships and trailing anchor elements.
        for (sheet_id, sheet_name, sheet_path) in sheet_entries {
            let rels_path = worksheet_rels_path(&sheet_path);
            let mut attach = SheetAttachments {
                orig_name: sheet_name,
                ..Default::default()
            };

            if let Some((srels_bytes, _)) = raw_entries.get(&rels_path) {
                for rel in parse_relationships(srels_bytes)? {
                    // IronCalc handles external hyperlinks natively; preserve everything else.
                    if !rel.rel_type.ends_with("/hyperlink") {
                        attach.extra_rels.push(rel);
                    }
                }
            }

            if let Some((ws_bytes, _)) = raw_entries.get(&sheet_path) {
                parse_worksheet_anchors(ws_bytes, &mut attach)?;
            }

            if !attach.extra_rels.is_empty()
                || attach.drawing_orig_rid.is_some()
                || attach.legacy_drawing_orig_rid.is_some()
                || !attach.table_part_orig_rids.is_empty()
                || !attach.preserved_ext_blocks.is_empty()
            {
                pkg.sheet_attachments.insert(sheet_id, attach);
            }
        }

        // 6. Parse chart formula references for integrity hazard checks.
        for (path, part) in &pkg.unknown_parts {
            if path.starts_with("xl/charts/chart") && path.ends_with(".xml") {
                pkg.chart_refs
                    .extend(parse_chart_formula_refs(path, &part.bytes));
            }
        }

        Ok(pkg)
    }

    /// Returns an iterator over all preserved unknown part paths and their raw payloads.
    pub fn unknown_parts(&self) -> &BTreeMap<String, PreservedPart> {
        &self.unknown_parts
    }
}

/// Returns `true` if `path` is one of the core OOXML parts regenerated by `IronCalcEngine`.
#[must_use]
pub fn is_engine_managed_part(path: &str) -> bool {
    let p = path.trim_start_matches('/');
    if matches!(
        p,
        "[Content_Types].xml"
            | "_rels/.rels"
            | "docProps/app.xml"
            | "docProps/core.xml"
            | "xl/workbook.xml"
            | "xl/_rels/workbook.xml.rels"
            | "xl/sharedStrings.xml"
            | "xl/styles.xml"
            | "xl/metadata.xml"
            | "xl/theme/theme1.xml"
    ) {
        return true;
    }
    if let Some(rest) = p.strip_prefix("xl/worksheets/sheet") {
        return rest
            .strip_suffix(".xml")
            .is_some_and(|n| !n.is_empty() && n.chars().all(|c| c.is_ascii_digit()));
    }
    if let Some(rest) = p.strip_prefix("xl/worksheets/_rels/sheet") {
        return rest
            .strip_suffix(".xml.rels")
            .is_some_and(|n| !n.is_empty() && n.chars().all(|c| c.is_ascii_digit()));
    }
    false
}

fn is_engine_root_rel_type(rel_type: &str) -> bool {
    rel_type.ends_with("/officeDocument")
        || rel_type.ends_with("/core-properties")
        || rel_type.ends_with("/extended-properties")
}

fn is_engine_workbook_rel_type(rel_type: &str) -> bool {
    rel_type.ends_with("/worksheet")
        || rel_type.ends_with("/styles")
        || rel_type.ends_with("/sharedStrings")
        || rel_type.ends_with("/sheetMetadata")
        || rel_type.ends_with("/theme")
}

fn normalize_xl_target(target: &str) -> String {
    if let Some(stripped) = target.strip_prefix('/') {
        stripped.to_string()
    } else if target.starts_with("xl/") {
        target.to_string()
    } else {
        format!("xl/{}", target.trim_start_matches("./"))
    }
}

fn worksheet_rels_path(sheet_path: &str) -> String {
    match sheet_path.rsplit_once('/') {
        Some((dir, file)) => format!("{dir}/_rels/{file}.rels"),
        None => format!("_rels/{sheet_path}.rels"),
    }
}

fn parse_content_types(bytes: &[u8], pkg: &mut PreservedPackage) -> Result<(), XlsxError> {
    let mut reader = Reader::from_reader(bytes);
    reader.config_mut().trim_text(true);
    let mut buf = Vec::new();
    let mut seen_defaults = BTreeSet::from(["rels".to_string(), "xml".to_string()]);

    loop {
        match reader.read_event_into(&mut buf) {
            Ok(Event::Empty(e) | Event::Start(e)) => match e.local_name().as_ref() {
                "Default" => {
                    let ext = attr_str(&e, "Extension")?;
                    let ct = attr_str(&e, "ContentType")?;
                    if let (Some(ext), Some(ct)) = (ext, ct)
                        && seen_defaults.insert(ext.to_ascii_lowercase())
                    {
                        pkg.extra_content_type_defaults.push((ext, ct));
                    }
                }
                "Override" => {
                    let part = attr_str(&e, "PartName")?;
                    let ct = attr_str(&e, "ContentType")?;
                    if let (Some(part), Some(ct)) = (part, ct) {
                        if part == "/xl/workbook.xml" {
                            pkg.workbook_content_type = Some(ct);
                        } else {
                            let norm = part.trim_start_matches('/');
                            if pkg.unknown_parts.contains_key(norm) {
                                pkg.extra_content_type_overrides.push((part, ct));
                            }
                        }
                    }
                }
                _ => {}
            },
            Ok(Event::Eof) => break,
            Err(err) => return Err(XlsxError::Xml(err.to_string())),
            _ => {}
        }
        buf.clear();
    }
    Ok(())
}

/// Parses an OPC `.rels` XML payload into [`RawRelationship`] items.
pub fn parse_relationships(bytes: &[u8]) -> Result<Vec<RawRelationship>, XlsxError> {
    let mut reader = Reader::from_reader(bytes);
    reader.config_mut().trim_text(true);
    let mut buf = Vec::new();
    let mut out = Vec::new();

    loop {
        match reader.read_event_into(&mut buf) {
            Ok(Event::Empty(e) | Event::Start(e)) if e.local_name().as_ref() == "Relationship" => {
                if let (Some(orig_id), Some(rel_type), Some(target)) = (
                    attr_str(&e, "Id")?,
                    attr_str(&e, "Type")?,
                    attr_str(&e, "Target")?,
                ) {
                    let target_mode = attr_str(&e, "TargetMode")?;
                    out.push(RawRelationship {
                        orig_id,
                        rel_type,
                        target,
                        target_mode,
                    });
                }
            }
            Ok(Event::Eof) => break,
            Err(err) => return Err(XlsxError::Xml(err.to_string())),
            _ => {}
        }
        buf.clear();
    }
    Ok(out)
}

fn parse_workbook_xml(
    bytes: &[u8],
    wb_rid_to_target: &BTreeMap<String, String>,
    sheet_entries: &mut Vec<(u32, String, String)>,
    pkg: &mut PreservedPackage,
) -> Result<(), XlsxError> {
    let xml_text = std::str::from_utf8(bytes).map_err(|e| XlsxError::Xml(e.to_string()))?;
    let mut reader = Reader::from_str(xml_text);
    let mut buf = Vec::new();

    loop {
        match reader.read_event_into(&mut buf) {
            Ok(Event::Empty(e) | Event::Start(e)) => match e.local_name().as_ref() {
                "workbookPr" => {
                    if let Some(code_name) = attr_str(&e, "codeName")? {
                        pkg.workbook_pr_xml =
                            Some(format!(r#"<workbookPr codeName="{code_name}"/>"#));
                    }
                }
                "sheet" => {
                    let name = attr_str(&e, "name")?.unwrap_or_default();
                    let sid = attr_str(&e, "sheetId")?
                        .and_then(|v| v.parse::<u32>().ok())
                        .unwrap_or(0);
                    let rid = attr_rid(&e)?;
                    if let Some(rid) = rid
                        && let Some(target) = wb_rid_to_target.get(&rid)
                    {
                        sheet_entries.push((sid, name, target.clone()));
                    }
                }
                "pivotCache" => {
                    if let (Some(cache_id), Some(orig_rid)) =
                        (attr_str(&e, "cacheId")?, attr_rid(&e)?)
                    {
                        let def_part = wb_rid_to_target.get(&orig_rid).cloned().unwrap_or_default();
                        pkg.pivot_caches.push(PivotCacheEntry {
                            cache_id,
                            orig_rid,
                            definition_part: def_part,
                            source_sheet: None,
                            source_ref: None,
                        });
                    }
                }
                _ => {}
            },
            Ok(Event::Eof) => break,
            Err(err) => return Err(XlsxError::Xml(err.to_string())),
            _ => {}
        }
        buf.clear();
    }

    pkg.workbook_ext_blocks = extract_ext_blocks(xml_text, false);
    Ok(())
}

fn parse_pivot_cache_source(bytes: &[u8]) -> Result<(Option<String>, Option<String>), XlsxError> {
    let mut reader = Reader::from_reader(bytes);
    let mut buf = Vec::new();
    loop {
        match reader.read_event_into(&mut buf) {
            Ok(Event::Empty(e) | Event::Start(e))
                if e.local_name().as_ref() == "worksheetSource" =>
            {
                let sheet = attr_str(&e, "sheet")?;
                let r = attr_str(&e, "ref")?;
                return Ok((sheet, r));
            }
            Ok(Event::Eof) => break,
            Err(err) => return Err(XlsxError::Xml(err.to_string())),
            _ => {}
        }
        buf.clear();
    }
    Ok((None, None))
}

fn parse_worksheet_anchors(bytes: &[u8], attach: &mut SheetAttachments) -> Result<(), XlsxError> {
    let xml_text = std::str::from_utf8(bytes).map_err(|e| XlsxError::Xml(e.to_string()))?;
    let mut reader = Reader::from_str(xml_text);
    let mut buf = Vec::new();

    loop {
        match reader.read_event_into(&mut buf) {
            Ok(Event::Empty(e) | Event::Start(e)) => match e.local_name().as_ref() {
                "drawing" => {
                    attach.drawing_orig_rid = attr_rid(&e)?;
                }
                "legacyDrawing" => {
                    attach.legacy_drawing_orig_rid = attr_rid(&e)?;
                }
                "tablePart" => {
                    if let Some(rid) = attr_rid(&e)? {
                        attach.table_part_orig_rids.push(rid);
                    }
                }
                _ => {}
            },
            Ok(Event::Eof) => break,
            Err(err) => return Err(XlsxError::Xml(err.to_string())),
            _ => {}
        }
        buf.clear();
    }

    attach.preserved_ext_blocks = extract_ext_blocks(xml_text, true);
    Ok(())
}

/// Extracts top-level `<ext ...>...</ext>` blocks inside `<extLst>...</extLst>`, optionally skipping
/// IronCalc-managed `conditionalFormattings` blocks on worksheets.
fn extract_ext_blocks(xml_text: &str, skip_conditional_formatting: bool) -> Vec<String> {
    let mut blocks = Vec::new();
    let Some(ext_lst_pos) = xml_text.rfind("<extLst") else {
        return blocks;
    };
    let tail = &xml_text[ext_lst_pos..];
    let Some(end_rel) = tail.find("</extLst>") else {
        return blocks;
    };
    let body = &tail[..end_rel];
    let mut cursor = 0;
    while let Some(rel_start) = body[cursor..].find("<ext ") {
        let abs_start = cursor + rel_start;
        if let Some(rel_close) = body[abs_start..].find("</ext>") {
            let abs_end = abs_start + rel_close + "</ext>".len();
            let snippet = &body[abs_start..abs_end];
            if !(skip_conditional_formatting && snippet.contains("conditionalFormattings")) {
                blocks.push(snippet.to_string());
            }
            cursor = abs_end;
        } else {
            break;
        }
    }
    blocks
}

fn parse_chart_formula_refs(chart_part: &str, bytes: &[u8]) -> Vec<ChartSourceRef> {
    let mut out = Vec::new();
    let Ok(xml_text) = std::str::from_utf8(bytes) else {
        return out;
    };
    let mut reader = Reader::from_str(xml_text);
    let mut buf = Vec::new();
    let mut inside_f = false;

    loop {
        match reader.read_event_into(&mut buf) {
            Ok(Event::Start(e)) if e.local_name().as_ref() == "f" => {
                inside_f = true;
            }
            Ok(Event::End(e)) if e.local_name().as_ref() == "f" => {
                inside_f = false;
            }
            Ok(Event::Text(t)) if inside_f => {
                let raw: &str = t.as_ref();
                if let Some((sheet_part, _rest)) = raw.split_once('!') {
                    let clean_sheet = sheet_part.trim_matches('\'').to_string();
                    if !clean_sheet.is_empty() {
                        out.push(ChartSourceRef {
                            chart_part: chart_part.to_string(),
                            sheet_name: clean_sheet,
                            formula_ref: raw.to_string(),
                        });
                    }
                }
            }
            Ok(Event::Eof) | Err(_) => break,
            _ => {}
        }
        buf.clear();
    }
    out
}

fn attr_str(
    e: &quick_xml::events::BytesStart<'_>,
    local_key: &str,
) -> Result<Option<String>, XlsxError> {
    for attr in e.attributes().with_checks(false) {
        let attr = attr.map_err(|err| XlsxError::Xml(err.to_string()))?;
        if attr.key.local_name().as_ref() == local_key {
            let val = attr
                .normalized_value(XmlVersion::Implicit1_0)
                .map_err(|err| XlsxError::Xml(err.to_string()))?;
            return Ok(Some(val.into_owned()));
        }
    }
    Ok(None)
}

fn attr_rid(e: &quick_xml::events::BytesStart<'_>) -> Result<Option<String>, XlsxError> {
    for attr in e.attributes().with_checks(false) {
        let attr = attr.map_err(|err| XlsxError::Xml(err.to_string()))?;
        if attr.key.as_ref() == "r:id" || attr.key.local_name().as_ref() == "id" {
            let val = attr
                .normalized_value(XmlVersion::Implicit1_0)
                .map_err(|err| XlsxError::Xml(err.to_string()))?;
            return Ok(Some(val.into_owned()));
        }
    }
    Ok(None)
}
